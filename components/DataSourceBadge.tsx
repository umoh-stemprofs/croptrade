// Data-source badge (design.md §2) — required by the Agriculture rules:
// every card that shows prices, weather or exchange rates says Live, Saved data,
// Simulated or Manual. Status is never color alone: color + icon + word.

export type BadgeSpec =
  | { kind: "live"; note?: string }
  | { kind: "saved"; ageLabel: string }
  | { kind: "simulated" }
  | { kind: "manual" };

function ClockIcon({ className }: { className: string }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.75"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={className}
    >
      <circle cx="12" cy="12" r="9" />
      <path d="M12 7v5l3 2" />
    </svg>
  );
}

function FlaskIcon({ className }: { className: string }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.75"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      className={className}
    >
      <path d="M9 3h6M10 3v6l-5.5 9.5A2 2 0 0 0 6.2 21h11.6a2 2 0 0 0 1.7-2.5L14 9V3" />
      <path d="M7.5 15h9" />
    </svg>
  );
}

const base =
  "inline-flex items-center gap-1.5 rounded-full border px-2.5 py-0.5 text-sm font-medium leading-5";

export function DataSourceBadge({ badge }: { badge: BadgeSpec }) {
  switch (badge.kind) {
    case "live":
      return (
        <span
          className={`${base} border-success/30 bg-success-bg text-success`}
          title="Fetched live from the provider"
        >
          <span className="h-2 w-2 rounded-full bg-success" aria-hidden="true" />
          Live{badge.note ? ` · ${badge.note}` : ""}
        </span>
      );
    case "saved":
      return (
        <span
          className={`${base} border-warning/30 bg-warning-bg text-warning`}
          title="Not fetched now — served from saved data"
        >
          <ClockIcon className="h-4 w-4" />
          Saved data · {badge.ageLabel}
        </span>
      );
    case "simulated":
      return (
        <span
          className={`${base} border-info/30 bg-info-bg text-info`}
          title="Generated by the app's simulated feed — sample data"
        >
          <FlaskIcon className="h-4 w-4" />
          Simulated
        </span>
      );
    case "manual":
      return (
        <span
          className={`${base} border-border bg-surface text-muted`}
          title="Rate typed in by the farmer"
        >
          <span className="h-2 w-2 rounded-full bg-muted" aria-hidden="true" />
          Manual
        </span>
      );
  }
}

export function OldRateTag() {
  return (
    <span
      className={`${base} border-warning/30 bg-warning-bg text-warning`}
      title="Old rate — older than 7 days. It still calculates."
    >
      <ClockIcon className="h-4 w-4" />
      Old rate
    </span>
  );
}
